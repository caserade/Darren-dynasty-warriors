'use strict';
const assert = require('assert'),
  fs = require('fs');
const { c, vm, elem, windowEvents, documentEvents } = require('./support.cjs');
const run = (s) => vm.runInContext(s, c);
const event = (id, type, pointerId, x = 54, y = 54) => {
  for (const fn of elem(id).listeners[type] || [])
    fn({ pointerId, clientX: x, clientY: y, button: 0, preventDefault() {} });
};
run("newGame();state='play';paused=false;dialogOpen=false;show(null)");
event('#stick', 'pointerdown', 1, 108, 54);
assert(run('stick.x===1&&stick.id===1'));
event('#stick', 'pointerdown', 2, 0, 54);
assert(run('stick.x===1&&stick.id===1'));
event('#tAtk', 'pointerdown', 2);
assert(run('brawlHeld&&attackPointer===2'));
event('#tAtk', 'pointerup', 3);
assert(run('brawlHeld&&attackPointer===2'));
event('#stick', 'pointerup', 1);
assert(run('stick.id===null&&stick.x===0&&brawlHeld'));
event('#tAtk', 'pointerup', 2);
assert(run('!brawlHeld&&attackPointer===null'));
console.log('PASS independent two-thumb movement/attack and pointer ownership');
event('#stick', 'pointerdown', 1, 108, 54);
event('#stick', 'lostpointercapture', 1);
assert(run('stick.x===0&&stick.id===null'));
run("P.weapon='snow';P.atk=null;P.shotCd=0;");
event('#tAtk', 'pointerdown', 2);
assert(run('chargeHeld'));
event('#tAtk', 'pointercancel', 2);
assert(run('!chargeHeld&&shots.length===0'));
event('#tAtk', 'pointerdown', 2);
run('chargeTime=.9');
event('#tAtk', 'pointerup', 2);
assert(run('shots.length===1&&!chargeHeld'));
console.log('PASS lost capture resets stick, canceled snow charge never fires, release fires once');
vm.runInContext(fs.readFileSync('dist/phone.js', 'utf8'), c);
run('P.shotCd=0');
event('#tAtk', 'pointerdown', 2);
event('#stick', 'pointerdown', 1, 108, 54);
windowEvents.orientationchange[0]();
assert(run('paused&&stick.id===null&&!chargeHeld&&attackPointer===null'));
event('#tAtk', 'pointerup', 2);
assert(run('shots.length===1'));
console.log('PASS rotation safely pauses and cancels held controls');
run('initPreferences();paused=false;isTouch=false;inputMode="keyboard"');
for (const fn of documentEvents.pointerdown) fn({ pointerType: 'touch' });
assert(run('isTouch&&inputMode==="touch"&&!$("#touch").hidden'));
console.log('PASS actual touch restores controls on hybrid devices');
